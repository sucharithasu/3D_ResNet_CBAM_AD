import scipy.ndimage

def center_crop_to_match(src, target_shape):
    src_shape = np.array(src.shape)
    tgt_shape = np.array(target_shape)
    start = ((src_shape - tgt_shape) / 2).astype(int)
    end = start + tgt_shape
    slices = tuple(slice(s, e) for s, e in zip(start, end))
    return src[slices]

